import java.math.BigInteger;

public class Count
{
    static final BigInteger THREE   = new BigInteger( "3" );
    static final BigInteger MaxLong = BigInteger.ONE.shiftLeft( 62 );
    static BigInteger TwoPowers[];
    static long counts[];
    static long distrib[];
    static int N;
 
    public static void main(String[] args)
    {
        N = Integer.parseInt( args[0] );
        counts = new long[ N+1 ];
        distrib = new long[ N+1 ];
        TwoPowers = new BigInteger[ N+1 ];
        for ( int n = 0; n < TwoPowers.length; ++n )
        {
            TwoPowers[n] = BigInteger.ONE.shiftLeft( n );
        }
        long totNew = 0;
        long noNewPrev = 1;
        System.out.format( "| $T_i$ | $N_i$ | $\\sum{N_i}$ | $\\left(N_i-N_{i-1}\\right)/N_{i-1}$ | Time,s |\n" );
        System.out.format( "|----:|-----------------:|-----------------:|---------:|-----:|\n" );
        for( int n = 0; n <= N; ++n )
        {
            long noNew = 0;
            long t1 = System.currentTimeMillis();
            BigInteger X = BigInteger.ONE.shiftLeft( n );
            if( n < 63 )
            {
                noNew =  dig( 1l << n, n );
            }
            else
            {
                noNew = dig( X, n );
            }
            long t2 = System.currentTimeMillis();
            totNew += noNew;
            double ll = (noNew - noNewPrev ) / (double)noNewPrev;
            System.out.format( "| %3d | %16d | %16d | %8.6f | %4d |\n", n, noNew, totNew, ll, ( t2 - t1 ) / 1000L );
            noNewPrev = noNew;
        }
        
        System.out.println();
        for( int i = 1; i <= N; ++i )
        {
            System.out.format( "| %3d | %16d | %16d |\n", i, counts[i], distrib[i] );
        }
    }

    static long dig( BigInteger X, int n )
    {
        long noNew = 1;
        for( int i = N; i > 0; --i )
        {
            if( TwoPowers[i].compareTo(X) >= 0 )
            {
                counts[i]++;
            }
            else
            {
                distrib[i]++;
                break;
            }
        }
        BigInteger quarter = X.shiftRight( 2 );
        for( int p2 = 0; p2 < n; ++p2 )
        {
            BigInteger sub = TwoPowers[ p2 ];
            if( sub.compareTo( quarter ) >= 0 )
            {
                break;
            }
            BigInteger next[] = X.subtract( sub ).divideAndRemainder( THREE );
            if( next[1].equals( BigInteger.ZERO ) )
            {
                if( next[0].compareTo( MaxLong ) <= 0 )
                {
                    noNew += dig( next[0].longValue(), p2 );
                }
                else
                {
                    noNew += dig( next[0], p2 );
                }
            }
        }
        return noNew;
    }

    static long dig( long X, int n )
    {
        int noNew = 1;
        for( int i = N; i > 0; --i )
        {
            if( i >= 63 || 1L << i >= X )
            {
                counts[i]++;
            }
            else
            {
                distrib[i]++;
                break;
            }
        }
        long quarter = X / 4L;
        for( int p2 = 0; p2 < n; ++p2 )
        {
            long sub = 1L << ( p2 );
            if( sub >= quarter )
            {
                break;
            }
            long next = X - sub;
            if( next % 3 == 0 )
            {
                noNew += dig( next / 3, p2 );
            }
        }
        return noNew;
    }
}


